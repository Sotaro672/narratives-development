// ListTransferCandidates returns records that may require a transfer task to be
// created or retried.
//
// The repository determines eligibility:
//   - ready
//   - failed_retryable
//   - stale transferring
func (u *BrandFeeSettlementUsecase) ListTransferCandidates(
	ctx context.Context,
	staleBefore time.Time,
	limit int,
) ([]brandfeesettlementdom.BrandFeeSettlement, error) {
	if err := u.validateRepositoryReady(); err != nil {
		return nil, err
	}
	if staleBefore.IsZero() {
		return nil, brandfeesettlementdom.ErrInvalidUpdatedAt
	}
	if limit <= 0 {
		return nil, ErrBrandFeeSettlementInvalidLimit
	}

	return u.repo.ListTransferCandidates(
		ctx,
		brandfeesettlementdom.ListTransferCandidatesInput{
			StaleBefore: staleBefore.UTC(),
			Limit:       limit,
		},
	)
}

// ============================================================
// Ensure pending
// ============================================================

// EnsurePending creates the BrandFeeSettlement corresponding to one successfully
// paid resale Order item.
//
// Deterministic PaymentID + OrderItemIndex identity makes this operation safe to
// repeat after payment webhook retries or partial application failures.
//
// If the document already exists, its lifecycle state is never rewound. The
// existing record is returned only when its immutable allocation exactly matches
// the requested Brand fee.
func (u *BrandFeeSettlementUsecase) EnsurePending(
	ctx context.Context,
	in EnsureBrandFeeSettlementInput,
) (*brandfeesettlementdom.BrandFeeSettlement, error) {
	if err := u.validateWriteReady(); err != nil {
		return nil, err
	}

	brandFeeSettlementID, err := brandfeesettlementdom.NewID(
		in.PaymentID,
		in.OrderItemIndex,
	)
	if err != nil {
		return nil, err
	}

	now := u.now().UTC()

	expected, err := brandfeesettlementdom.New(
		brandFeeSettlementID,
		in.OrderID,
		in.PaymentID,
		in.OrderItemIndex,
		in.ResaleID,
		in.Brand,
		in.StripePaymentIntentID,
		in.StripeChargeID,
		in.TransferGroup,
		in.BrandFeeAmount,
		in.Currency,
		now,
	)
	if err != nil {
		return nil, err
	}

	created, err := u.repo.Create(
		ctx,
		brandfeesettlementdom.CreateBrandFeeSettlementInput{
			BrandFeeSettlementID:  brandFeeSettlementID,
			OrderID:               in.OrderID,
			PaymentID:             in.PaymentID,
			OrderItemIndex:        in.OrderItemIndex,
			ResaleID:              in.ResaleID,
			Brand:                 in.Brand,
			StripePaymentIntentID: in.StripePaymentIntentID,
			StripeChargeID:        in.StripeChargeID,
			TransferGroup:         in.TransferGroup,
			BrandFeeAmount:        in.BrandFeeAmount,
			Currency:              in.Currency,
			Status:                brandfeesettlementdom.StatusPending,
		},
	)
	if err == nil {
		if err := validateCreatedBrandFeeSettlement(created, expected); err != nil {
			return nil, err
		}

		return &created, nil
	}
	if !errors.Is(err, brandfeesettlementdom.ErrConflict) {
		return nil, err
	}

	existing, getErr := u.repo.GetByID(ctx, brandFeeSettlementID)
	if getErr != nil {
		return nil, getErr
	}
	if err := validateExistingBrandFeeSettlementAllocation(existing, expected); err != nil {
		return nil, err
	}

	return &existing, nil
}

// ============================================================
// Fulfillment boundary
// ============================================================

// MarkReady transitions one pending BrandFeeSettlement to ready after the exact
// resale Order item crosses the fulfillment boundary.
//
// Repeated execution is idempotent after the boundary has already been crossed.
// A canceled Brand fee cannot be reopened.
func (u *BrandFeeSettlementUsecase) MarkReady(
	ctx context.Context,
	brandFeeSettlementID string,
) (*brandfeesettlementdom.BrandFeeSettlement, error) {
	if err := u.validateWriteReady(); err != nil {
		return nil, err
	}
	if brandFeeSettlementID == "" {
		return nil, brandfeesettlementdom.ErrInvalidID
	}

	current, err := u.repo.GetByID(ctx, brandFeeSettlementID)
	if err != nil {
		return nil, err
	}
	if err := current.Validate(); err != nil {
		return nil, err
	}

	switch current.Status {
	case brandfeesettlementdom.StatusPending:
		nextStatus := brandfeesettlementdom.StatusReady
		updated, err := u.repo.UpdateByID(
			ctx,
			brandFeeSettlementID,
			brandfeesettlementdom.UpdateBrandFeeSettlementInput{
				Status: &nextStatus,
			},
		)
		if err != nil {
			return nil, err
		}
		if err := updated.Validate(); err != nil {
			return nil, err
		}

		return &updated, nil

	case brandfeesettlementdom.StatusReady,
		brandfeesettlementdom.StatusTransferring,
		brandfeesettlementdom.StatusTransferred,
		brandfeesettlementdom.StatusFailedRetryable,
		brandfeesettlementdom.StatusFailed,
		brandfeesettlementdom.StatusReversed:
		return &current, nil

	case brandfeesettlementdom.StatusCanceled:
		return nil, ErrBrandFeeSettlementCannotReady

	default:
		return nil, brandfeesettlementdom.ErrInvalidStatus
	}
}

// ============================================================
// Cancellation
// ============================================================

// Cancel cancels a Brand fee before a successful Stripe Transfer.
//
// pending, ready, and failed_retryable may become canceled according to the
// domain lifecycle.
//
// A repeated cancellation is idempotent.
//
// transferring cannot be canceled because the Stripe request result must first
// be reconciled. transferred requires Stripe Transfer reversal rather than
// cancellation.
func (u *BrandFeeSettlementUsecase) Cancel(
	ctx context.Context,
	brandFeeSettlementID string,
) (*brandfeesettlementdom.BrandFeeSettlement, error) {
	if err := u.validateWriteReady(); err != nil {
		return nil, err
	}
	if brandFeeSettlementID == "" {
		return nil, brandfeesettlementdom.ErrInvalidID
	}

	current, err := u.repo.GetByID(ctx, brandFeeSettlementID)
	if err != nil {
		return nil, err
	}
	if err := current.Validate(); err != nil {
		return nil, err
	}

	switch current.Status {
	case brandfeesettlementdom.StatusPending,
		brandfeesettlementdom.StatusReady,
		brandfeesettlementdom.StatusFailedRetryable:
		nextStatus := brandfeesettlementdom.StatusCanceled
		updated, err := u.repo.UpdateByID(
			ctx,
			brandFeeSettlementID,
			brandfeesettlementdom.UpdateBrandFeeSettlementInput{
				Status: &nextStatus,
			},
		)
		if err != nil {
			return nil, err
		}
		if err := updated.Validate(); err != nil {
			return nil, err
		}

		return &updated, nil

	case brandfeesettlementdom.StatusCanceled:
		return &current, nil

	case brandfeesettlementdom.StatusTransferring,
		brandfeesettlementdom.StatusTransferred,
		brandfeesettlementdom.StatusFailed,
		brandfeesettlementdom.StatusReversed:
		return nil, ErrBrandFeeSettlementCannotCancel

	default:
		return nil, brandfeesettlementdom.ErrInvalidStatus
	}
}

// ============================================================
// Validation
// ============================================================

func validateCreatedBrandFeeSettlement(
	actual brandfeesettlementdom.BrandFeeSettlement,
	expected brandfeesettlementdom.BrandFeeSettlement,
) error {
	if err := actual.Validate(); err != nil {
		return err
	}
	if actual.Status != brandfeesettlementdom.StatusPending {
		return ErrBrandFeeSettlementExistingMismatch
	}

	return validateExistingBrandFeeSettlementAllocation(actual, expected)
}

func validateExistingBrandFeeSettlementAllocation(
	actual brandfeesettlementdom.BrandFeeSettlement,
	expected brandfeesettlementdom.BrandFeeSettlement,
) error {
	if err := actual.Validate(); err != nil {
		return err
	}
	if err := expected.Validate(); err != nil {
		return err
	}

	if actual.ID != expected.ID ||
		actual.OrderID != expected.OrderID ||
		actual.PaymentID != expected.PaymentID ||
		actual.OrderItemIndex != expected.OrderItemIndex ||
		actual.ResaleID != expected.ResaleID ||
		actual.BrandID != expected.BrandID ||
		actual.CompanyID != expected.CompanyID ||
		actual.AccountID != expected.AccountID ||
		actual.StripeAccountID != expected.StripeAccountID ||
		actual.StripePaymentIntentID != expected.StripePaymentIntentID ||
		actual.StripeChargeID != expected.StripeChargeID ||
		actual.TransferGroup != expected.TransferGroup ||
		actual.BrandFeeAmount != expected.BrandFeeAmount ||
		actual.Currency != expected.Currency {
		return ErrBrandFeeSettlementExistingMismatch
	}

	expectedID, err := brandfeesettlementdom.NewID(
		actual.PaymentID,
		actual.OrderItemIndex,
	)
	if err != nil {
		return err
	}
	if actual.ID != expectedID {
		return ErrBrandFeeSettlementExistingMismatch
	}

	return nil
}

func (u *BrandFeeSettlementUsecase) validateRepositoryReady() error {
	if u == nil || u.repo == nil {
		return ErrBrandFeeSettlementRepositoryMissing
	}

	return nil
}

func (u *BrandFeeSettlementUsecase) validateWriteReady() error {
	if err := u.validateRepositoryReady(); err != nil {
		return err
	}
	if u.now == nil {
		return ErrBrandFeeSettlementClockMissing
	}

	return nil
}
