var (
	ErrBrandFeeSettlementRepositoryMissing = errors.New("brandFeeSettlement: repository is not configured")
	ErrBrandFeeSettlementClockMissing      = errors.New("brandFeeSettlement: clock is not configured")
	ErrBrandFeeSettlementExistingMismatch  = errors.New("brandFeeSettlement: existing settlement does not match requested allocation")
	ErrBrandFeeSettlementCannotReady       = errors.New("brandFeeSettlement: settlement cannot become ready")
	ErrBrandFeeSettlementCannotCancel      = errors.New("brandFeeSettlement: settlement cannot be canceled")
	ErrBrandFeeSettlementInvalidLimit      = errors.New("brandFeeSettlement: invalid list limit")
)

// ============================================================
// Transfer repository port
// ============================================================

// BrandFeeSettlementTransferRepository extends the domain repository with the
// atomic operations required by the Brand fee Stripe Transfer worker.
//
// Stripe Transfer execution must never use a plain GetByID followed by a
// non-transactional status update. ClaimForTransfer must atomically establish
// ownership of the transfer attempt.
//
// The Firestore implementation is expected to provide these methods in addition
// to brandFeeSettlement.Repository.
type BrandFeeSettlementTransferRepository interface {
	brandfeesettlementdom.Repository

	ClaimForTransfer(
		ctx context.Context,
		brandFeeSettlementID string,
		now time.Time,
		staleBefore time.Time,
	) (brandfeesettlementdom.BrandFeeSettlement, bool, error)

	CompleteTransfer(
		ctx context.Context,
		brandFeeSettlementID string,
		stripeTransferID string,
		now time.Time,
	) (brandfeesettlementdom.BrandFeeSettlement, error)

	FailTransfer(
		ctx context.Context,
		brandFeeSettlementID string,
		status brandfeesettlementdom.Status,
		errorType *string,
		errorCode *string,
		errorMsg *string,
		now time.Time,
	) (brandfeesettlementdom.BrandFeeSettlement, error)

	ReverseTransfer(
		ctx context.Context,
		brandFeeSettlementID string,
		stripeTransferReversalID string,
		now time.Time,
	) (brandfeesettlementdom.BrandFeeSettlement, error)
}

// ============================================================
// Ensure input
// ============================================================

// EnsureBrandFeeSettlementInput represents the productBlueprint Brand share
// generated by one successfully paid resale Order item.
//
// One resale Order item creates exactly one BrandFeeSettlement.
//
// Brand is the immutable payout destination captured in the Order item's
// BrandRevenueSnapshot. Current Brand or Account state must never be re-resolved
// to alter this destination.
//
// BrandFeeAmount has already been calculated by settlement.Calculator. This
// usecase does not recalculate the percentage.
//
// The resulting document ID is deterministic:
//
//	PaymentID + "_resale_brand_fee_item_" + OrderItemIndex
//
// EnsurePending is idempotent. If that document already exists, it is accepted
// only when every immutable allocation field matches exactly.
type EnsureBrandFeeSettlementInput struct {
	OrderID        string
	PaymentID      string
	OrderItemIndex int
	ResaleID       string

	Brand brandfeesettlementdom.BrandIdentity

	StripePaymentIntentID string
	StripeChargeID        string

	TransferGroup string

	BrandFeeAmount int

	Currency string
}

// ============================================================
// Usecase
// ============================================================

// BrandFeeSettlementUsecase manages the productBlueprint Brand share generated
// by consumer resale transactions.
//
// Responsibilities:
//   - create one pending BrandFeeSettlement for each successfully paid resale item
//   - guarantee idempotent payment-success processing
//   - provide authoritative reads
//   - mark the exact Brand fee ready after the fulfillment boundary
//   - cancel a Brand fee before Stripe Transfer when permitted
//
// Actual Stripe Transfer execution is intentionally separate and must use
// BrandFeeSettlementTransferRepository so transfer claims are atomic.
type BrandFeeSettlementUsecase struct {
	repo brandfeesettlementdom.Repository
	now  func() time.Time
}

func NewBrandFeeSettlementUsecase(
	repo brandfeesettlementdom.Repository,
) *BrandFeeSettlementUsecase {
	return &BrandFeeSettlementUsecase{
		repo: repo,
		now:  time.Now,
	}
}

// ============================================================
// Read
// ============================================================

// GetByID returns one persisted BrandFeeSettlement.
func (u *BrandFeeSettlementUsecase) GetByID(
	ctx context.Context,
	brandFeeSettlementID string,
) (*brandfeesettlementdom.BrandFeeSettlement, error) {
	if err := u.validateRepositoryReady(); err != nil {
		return nil, err
	}
	if brandFeeSettlementID == "" {
		return nil, brandfeesettlementdom.ErrInvalidID
	}

	settlement, err := u.repo.GetByID(ctx, brandFeeSettlementID)
	if err != nil {
		return nil, err
	}
	if settlement.ID != brandFeeSettlementID {
		return nil, brandfeesettlementdom.ErrInvalidID
	}
	if err := settlement.Validate(); err != nil {
		return nil, err
	}

	return &settlement, nil
}

