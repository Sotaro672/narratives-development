package cloudtasks

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"net/url"
	"os"
	"strings"
	"time"

	cloudtasksv2 "cloud.google.com/go/cloudtasks/apiv2"
	taskspb "cloud.google.com/go/cloudtasks/apiv2/cloudtaskspb"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
	"google.golang.org/protobuf/types/known/durationpb"

	brandfeesettlementdom "narratives/internal/domain/brandFeeSettlement"
)

const (
	envBrandFeeSettlementCloudTasksProjectID      = "CLOUD_TASKS_PROJECT_ID"
	envBrandFeeSettlementCloudTasksLocation       = "CLOUD_TASKS_LOCATION"
	envBrandFeeSettlementCloudTasksQueueID        = "BRAND_FEE_SETTLEMENT_CLOUD_TASKS_QUEUE_ID"
	envBrandFeeSettlementInternalBaseURL          = "INTERNAL_BASE_URL"
	envBrandFeeSettlementCloudTasksServiceAccount = "CLOUD_TASKS_SERVICE_ACCOUNT"
	envBrandFeeSettlementCloudTasksAudience       = "CLOUD_TASKS_AUDIENCE"

	defaultBrandFeeSettlementTaskPath = "/internal/brand-fee-settlements/process"

	defaultBrandFeeSettlementDispatchDeadline = 10 * time.Minute
)

// ============================================================
// Config
// ============================================================

type BrandFeeSettlementQueueConfig struct {
	ProjectID string
	Location  string
	QueueID   string

	InternalBaseURL string

	ServiceAccountEmail string
	Audience            string
}

// ============================================================
// Payload
// ============================================================

// brandFeeSettlementTaskPayload intentionally contains only
// BrandFeeSettlementID.
//
// BrandFeeAmount, Brand identity, destination Stripe Account, Charge ID,
// TransferGroup, and every other financial field must be loaded again from the
// authoritative BrandFeeSettlement document by the worker.
type brandFeeSettlementTaskPayload struct {
	BrandFeeSettlementID string `json:"brandFeeSettlementId"`
}

// ============================================================
// BrandFeeSettlementQueue
// ============================================================

// BrandFeeSettlementQueue enqueues Stripe Connect Transfer processing for
// productBlueprint Brand fees generated by resale transactions.
//
// Cloud Tasks delivery is at-least-once.
//
// Duplicate Stripe money movement is prevented by:
//  1. BrandFeeSettlementRepositoryFS.ClaimForTransfer
//  2. deterministic Stripe Idempotency-Key
//
// The queue is intentionally separate from primary Settlement processing.
type BrandFeeSettlementQueue struct {
	client *cloudtasksv2.Client

	queuePath string
	targetURL string

	serviceAccountEmail string
	audience            string

	dispatchDeadline time.Duration
}

// NewBrandFeeSettlementQueueFromEnv creates BrandFeeSettlementQueue from
// environment configuration.
//
// Required:
//
//	CLOUD_TASKS_PROJECT_ID
//	CLOUD_TASKS_LOCATION
//	BRAND_FEE_SETTLEMENT_CLOUD_TASKS_QUEUE_ID
//	INTERNAL_BASE_URL
//	CLOUD_TASKS_SERVICE_ACCOUNT
//
// Optional:
//
//	CLOUD_TASKS_AUDIENCE
//
// When CLOUD_TASKS_AUDIENCE is empty, INTERNAL_BASE_URL is used.
func NewBrandFeeSettlementQueueFromEnv(
	ctx context.Context,
) (*BrandFeeSettlementQueue, error) {
	config := BrandFeeSettlementQueueConfig{
		ProjectID: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementCloudTasksProjectID,
			"GCP_PROJECT_ID",
			"GOOGLE_CLOUD_PROJECT",
		),
		Location: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementCloudTasksLocation,
		),
		QueueID: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementCloudTasksQueueID,
		),
		InternalBaseURL: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementInternalBaseURL,
		),
		ServiceAccountEmail: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementCloudTasksServiceAccount,
		),
		Audience: firstNonEmptyBrandFeeSettlementEnv(
			envBrandFeeSettlementCloudTasksAudience,
		),
	}

	return NewBrandFeeSettlementQueue(
		ctx,
		config,
	)
}

// NewBrandFeeSettlementQueue creates BrandFeeSettlementQueue from explicit
// configuration.
func NewBrandFeeSettlementQueue(
	ctx context.Context,
	config BrandFeeSettlementQueueConfig,
) (*BrandFeeSettlementQueue, error) {
	normalizedConfig, err := normalizeBrandFeeSettlementQueueConfig(config)
	if err != nil {
		return nil, err
	}

	if ctx == nil {
		ctx = context.Background()
	}

	client, err := cloudtasksv2.NewClient(ctx)
	if err != nil {
		return nil, fmt.Errorf(
			"create brand fee settlement Cloud Tasks client: %w",
			err,
		)
	}

	queuePath := fmt.Sprintf(
		"projects/%s/locations/%s/queues/%s",
		normalizedConfig.ProjectID,
		normalizedConfig.Location,
		normalizedConfig.QueueID,
	)

	targetURL := strings.TrimRight(
		normalizedConfig.InternalBaseURL,
		"/",
	) + defaultBrandFeeSettlementTaskPath

	return &BrandFeeSettlementQueue{
		client:              client,
		queuePath:           queuePath,
		targetURL:           targetURL,
		serviceAccountEmail: normalizedConfig.ServiceAccountEmail,
		audience:            normalizedConfig.Audience,
		dispatchDeadline:    defaultBrandFeeSettlementDispatchDeadline,
	}, nil
}

// ============================================================
// Enqueue
// ============================================================

// EnqueueBrandFeeSettlementTransfer creates the Cloud Task that executes one
// BrandFeeSettlement Stripe Connect Transfer.
//
// The task name is deterministic from BrandFeeSettlementID. Repeated enqueue
// calls for the same financial record therefore treat Cloud Tasks AlreadyExists
// as success.
//
// Retryable Stripe failures should cause the worker to return a non-2xx
// response. Cloud Tasks then retries this same task according to the queue's
// retry configuration.
func (q *BrandFeeSettlementQueue) EnqueueBrandFeeSettlementTransfer(
	ctx context.Context,
	brandFeeSettlementID string,
) error {
	if q == nil {
		return errors.New("brand fee settlement queue is nil")
	}
	if q.client == nil {
		return errors.New("brand fee settlement Cloud Tasks client is nil")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if brandFeeSettlementID == "" ||
		strings.Contains(brandFeeSettlementID, "/") {
		return brandfeesettlementdom.ErrInvalidID
	}

	payload, err := json.Marshal(
		brandFeeSettlementTaskPayload{
			BrandFeeSettlementID: brandFeeSettlementID,
		},
	)
	if err != nil {
		return fmt.Errorf(
			"marshal brand fee settlement task payload: %w",
			err,
		)
	}

	taskID := buildBrandFeeSettlementTaskID(
		brandFeeSettlementID,
	)

	taskName := fmt.Sprintf(
		"%s/tasks/%s",
		q.queuePath,
		taskID,
	)

	httpRequest := &taskspb.HttpRequest{
		HttpMethod: taskspb.HttpMethod_POST,
		Url:        q.targetURL,
		Headers: map[string]string{
			"Content-Type": "application/json",
		},
		Body: payload,
		AuthorizationHeader: &taskspb.HttpRequest_OidcToken{
			OidcToken: &taskspb.OidcToken{
				ServiceAccountEmail: q.serviceAccountEmail,
				Audience:            q.audience,
			},
		},
	}

	task := &taskspb.Task{
		Name: taskName,
		MessageType: &taskspb.Task_HttpRequest{
			HttpRequest: httpRequest,
		},
		DispatchDeadline: durationpb.New(
			q.normalizedDispatchDeadline(),
		),
	}

	_, err = q.client.CreateTask(
		ctx,
		&taskspb.CreateTaskRequest{
			Parent: q.queuePath,
			Task:   task,
		},
	)
	if err != nil {
		if status.Code(err) == codes.AlreadyExists {
			return nil
		}

		return fmt.Errorf(
			"create brand fee settlement task brandFeeSettlementId=%q: %w",
			brandFeeSettlementID,
			err,
		)
	}

	return nil
}

// ============================================================
// Close
// ============================================================

func (q *BrandFeeSettlementQueue) Close() error {
	if q == nil || q.client == nil {
		return nil
	}

	if err := q.client.Close(); err != nil {
		return fmt.Errorf(
			"close brand fee settlement Cloud Tasks client: %w",
			err,
		)
	}

	q.client = nil
	return nil
}

// ============================================================
// Config normalization
// ============================================================

func normalizeBrandFeeSettlementQueueConfig(
	config BrandFeeSettlementQueueConfig,
) (BrandFeeSettlementQueueConfig, error) {
	config.InternalBaseURL = strings.TrimRight(
		config.InternalBaseURL,
		"/",
	)
	config.Audience = strings.TrimRight(
		config.Audience,
		"/",
	)

	if config.ProjectID == "" {
		return BrandFeeSettlementQueueConfig{},
			errors.New("CLOUD_TASKS_PROJECT_ID is empty")
	}
	if config.Location == "" {
		return BrandFeeSettlementQueueConfig{},
			errors.New("CLOUD_TASKS_LOCATION is empty")
	}
	if config.QueueID == "" {
		return BrandFeeSettlementQueueConfig{},
			errors.New("BRAND_FEE_SETTLEMENT_CLOUD_TASKS_QUEUE_ID is empty")
	}
	if config.InternalBaseURL == "" {
		return BrandFeeSettlementQueueConfig{},
			errors.New("INTERNAL_BASE_URL is empty")
	}
	if err := validateBrandFeeSettlementQueueURL(
		config.InternalBaseURL,
	); err != nil {
		return BrandFeeSettlementQueueConfig{},
			fmt.Errorf(
				"invalid INTERNAL_BASE_URL: %w",
				err,
			)
	}
	if config.ServiceAccountEmail == "" {
		return BrandFeeSettlementQueueConfig{},
			errors.New("CLOUD_TASKS_SERVICE_ACCOUNT is empty")
	}
	if config.Audience == "" {
		config.Audience = config.InternalBaseURL
	}
	if err := validateBrandFeeSettlementQueueURL(
		config.Audience,
	); err != nil {
		return BrandFeeSettlementQueueConfig{},
			fmt.Errorf(
				"invalid CLOUD_TASKS_AUDIENCE: %w",
				err,
			)
	}

	return config, nil
}

// ============================================================
// URL validation
// ============================================================

func validateBrandFeeSettlementQueueURL(
	value string,
) error {
	if value == "" {
		return errors.New("URL is empty")
	}

	parsed, err := url.ParseRequestURI(value)
	if err != nil {
		return fmt.Errorf(
			"parse URL: %w",
			err,
		)
	}

	switch strings.ToLower(parsed.Scheme) {
	case "http", "https":
	default:
		return errors.New("URL must use http or https")
	}

	if parsed.Host == "" {
		return errors.New("URL host is empty")
	}
	if parsed.RawQuery != "" {
		return errors.New("URL must not contain query parameters")
	}
	if parsed.Fragment != "" {
		return errors.New("URL must not contain fragment")
	}

	return nil
}

// ============================================================
// Task ID
// ============================================================

// buildBrandFeeSettlementTaskID creates a Cloud Tasks-safe deterministic task
// ID.
//
// BrandFeeSettlementID itself is not exposed as the Cloud Tasks task name.
// SHA-256 also keeps the task name short and deterministic.
func buildBrandFeeSettlementTaskID(
	brandFeeSettlementID string,
) string {
	digest := sha256.Sum256(
		[]byte(brandFeeSettlementID),
	)

	settlementHash := hex.EncodeToString(
		digest[:16],
	)

	return fmt.Sprintf(
		"brand-fee-settlement-%s",
		settlementHash,
	)
}

// ============================================================
// Environment
// ============================================================

func firstNonEmptyBrandFeeSettlementEnv(
	keys ...string,
) string {
	for _, key := range keys {
		if key == "" {
			continue
		}

		value := os.Getenv(key)
		if value != "" {
			return value
		}
	}

	return ""
}

// ============================================================
// Deadline
// ============================================================

func (q *BrandFeeSettlementQueue) normalizedDispatchDeadline() time.Duration {
	if q == nil || q.dispatchDeadline <= 0 {
		return defaultBrandFeeSettlementDispatchDeadline
	}

	return q.dispatchDeadline
}
