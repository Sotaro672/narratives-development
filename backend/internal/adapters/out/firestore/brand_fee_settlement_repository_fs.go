// ClaimForTransfer atomically claims one BrandFeeSettlement for Stripe Transfer.
//
// ready and failed_retryable may be claimed immediately.
//
// transferring may be reclaimed only when UpdatedAt <= staleBefore. This
// recovers worker failure after the claim was persisted but before the Stripe
// result was stored.
//
// The Stripe caller must use a deterministic idempotency key so reclaiming a
// stale record cannot intentionally create a second transfer.
func (r *BrandFeeSettlementRepositoryFS) ClaimForTransfer(
	ctx context.Context,
	brandFeeSettlementID string,
	now time.Time,
	staleBefore time.Time,
) (brandfeesettlementdom.BrandFeeSettlement, bool, error) {
	if r == nil || r.Client == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if brandFeeSettlementID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidID
	}
	if now.IsZero() || staleBefore.IsZero() {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidUpdatedAt
	}

	now = now.UTC()
	staleBefore = staleBefore.UTC()
	if !staleBefore.Before(now) {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidUpdatedAt
	}

	documentReference := r.doc(brandFeeSettlementID)
	var result brandfeesettlementdom.BrandFeeSettlement
	claimed := false

	err := r.Client.RunTransaction(ctx, func(ctx context.Context, transaction *firestore.Transaction) error {
		snapshot, err := transaction.Get(documentReference)
		if err != nil {
			if status.Code(err) == codes.NotFound {
				return brandfeesettlementdom.ErrNotFound
			}
			return err
		}

		current, err := docToBrandFeeSettlement(snapshot)
		if err != nil {
			return err
		}

		next := current

		switch current.Status {
		case brandfeesettlementdom.StatusReady, brandfeesettlementdom.StatusFailedRetryable:
			if err := next.StartTransfer(now); err != nil {
				return err
			}

		case brandfeesettlementdom.StatusTransferring:
			if current.UpdatedAt.After(staleBefore) {
				result = current
				claimed = false
				return nil
			}
			if err := next.ReclaimTransfer(now); err != nil {
				return err
			}

		default:
			result = current
			claimed = false
			return nil
		}

		if err := validateBrandFeeSettlementImmutableFields(current, next); err != nil {
			return err
		}
		if err := transaction.Set(documentReference, brandFeeSettlementToData(next)); err != nil {
			return err
		}

		result = next
		claimed = true
		return nil
	})
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, err
	}

	return result, claimed, nil
}

// CompleteTransfer atomically records a successful Stripe Connect Transfer.
//
// Repeating the same completion with the same StripeTransferID is an idempotent
// no-op.
func (r *BrandFeeSettlementRepositoryFS) CompleteTransfer(
	ctx context.Context,
	brandFeeSettlementID string,
	stripeTransferID string,
	now time.Time,
) (brandfeesettlementdom.BrandFeeSettlement, error) {
	if r == nil || r.Client == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if brandFeeSettlementID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidID
	}
	if stripeTransferID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidStripeTransferID
	}
	if now.IsZero() {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidTransferredAt
	}

	now = now.UTC()
	documentReference := r.doc(brandFeeSettlementID)
	var result brandfeesettlementdom.BrandFeeSettlement

	err := r.Client.RunTransaction(ctx, func(ctx context.Context, transaction *firestore.Transaction) error {
		snapshot, err := transaction.Get(documentReference)
		if err != nil {
			if status.Code(err) == codes.NotFound {
				return brandfeesettlementdom.ErrNotFound
			}
			return err
		}

		current, err := docToBrandFeeSettlement(snapshot)
		if err != nil {
			return err
		}

		if current.Status == brandfeesettlementdom.StatusTransferred {
			if current.StripeTransferID == stripeTransferID {
				result = current
				return nil
			}
			return brandfeesettlementdom.ErrInvalidStripeTransferID
		}
		if current.Status != brandfeesettlementdom.StatusTransferring {
			return brandfeesettlementdom.ErrInvalidStatusTransition
		}

		next := current
		if err := next.MarkTransferred(stripeTransferID, now); err != nil {
			return err
		}
		if err := validateBrandFeeSettlementImmutableFields(current, next); err != nil {
			return err
		}
		if err := transaction.Set(documentReference, brandFeeSettlementToData(next)); err != nil {
			return err
		}

		result = next
		return nil
	})
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}

	return result, nil
}

// FailTransfer atomically records a retryable or terminal Stripe Transfer
// failure.
//
// Repeating an identical already-recorded failure is an idempotent no-op.
func (r *BrandFeeSettlementRepositoryFS) FailTransfer(
	ctx context.Context,
	brandFeeSettlementID string,
	nextStatus brandfeesettlementdom.Status,
	errorType *string,
	errorCode *string,
	errorMsg *string,
	now time.Time,
) (brandfeesettlementdom.BrandFeeSettlement, error) {
	if r == nil || r.Client == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if brandFeeSettlementID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidID
	}
	if nextStatus != brandfeesettlementdom.StatusFailedRetryable &&
		nextStatus != brandfeesettlementdom.StatusFailed {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidStatusTransition
	}

	errorType = normalizeBrandFeeSettlementOptionalString(errorType)
	errorCode = normalizeBrandFeeSettlementOptionalString(errorCode)
	errorMsg = normalizeBrandFeeSettlementOptionalString(errorMsg)

	if errorType == nil && errorCode == nil && errorMsg == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrFailureReasonRequired
	}
	if now.IsZero() {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidUpdatedAt
	}

	now = now.UTC()
	documentReference := r.doc(brandFeeSettlementID)
	var result brandfeesettlementdom.BrandFeeSettlement

	err := r.Client.RunTransaction(ctx, func(ctx context.Context, transaction *firestore.Transaction) error {
		snapshot, err := transaction.Get(documentReference)
		if err != nil {
			if status.Code(err) == codes.NotFound {
				return brandfeesettlementdom.ErrNotFound
			}
			return err
		}

		current, err := docToBrandFeeSettlement(snapshot)
		if err != nil {
			return err
		}

		if current.Status == nextStatus &&
			brandFeeSettlementOptionalStringEqual(current.ErrorType, errorType) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorCode, errorCode) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorMsg, errorMsg) {
			result = current
			return nil
		}
		if current.Status != brandfeesettlementdom.StatusTransferring {
			return brandfeesettlementdom.ErrInvalidStatusTransition
		}

		next := current
		switch nextStatus {
		case brandfeesettlementdom.StatusFailedRetryable:
			err = next.MarkFailedRetryable(errorType, errorCode, errorMsg, now)
		case brandfeesettlementdom.StatusFailed:
			err = next.MarkFailed(errorType, errorCode, errorMsg, now)
		}
		if err != nil {
			return err
		}
		if err := validateBrandFeeSettlementImmutableFields(current, next); err != nil {
			return err
		}
		if err := transaction.Set(documentReference, brandFeeSettlementToData(next)); err != nil {
			return err
		}

		result = next
		return nil
	})
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}

	return result, nil
}

// ReverseTransfer atomically records a completed Stripe Transfer reversal.
//
// Repeating the same reversal ID is an idempotent no-op.
