// ============================================================
// Update patch
// ============================================================

func applyBrandFeeSettlementPatch(
	current brandfeesettlementdom.BrandFeeSettlement,
	patch brandfeesettlementdom.UpdateBrandFeeSettlementInput,
	now time.Time,
) (brandfeesettlementdom.BrandFeeSettlement, bool, error) {
	if patch.Status == nil {
		if patch.StripeTransferID != nil ||
			patch.StripeTransferReversalID != nil ||
			patch.ErrorType != nil ||
			patch.ErrorCode != nil ||
			patch.ErrorMsg != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStatusTransition
		}
		return current, false, nil
	}
	if now.IsZero() {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidUpdatedAt
	}

	now = now.UTC()
	nextStatus := *patch.Status

	if current.Status == nextStatus &&
		patch.StripeTransferID == nil &&
		patch.StripeTransferReversalID == nil &&
		patch.ErrorType == nil &&
		patch.ErrorCode == nil &&
		patch.ErrorMsg == nil {
		return current, false, nil
	}

	next := current

	switch nextStatus {
	case brandfeesettlementdom.StatusPending:
		if current.Status != brandfeesettlementdom.StatusPending {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStatusTransition
		}
		return current, false, nil

	case brandfeesettlementdom.StatusReady:
		if err := next.MarkReady(now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusTransferring:
		if current.Status == brandfeesettlementdom.StatusTransferring {
			return current, false, nil
		}
		if err := next.StartTransfer(now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusTransferred:
		if patch.StripeTransferID == nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferID
		}

		stripeTransferID := *patch.StripeTransferID
		if current.Status == brandfeesettlementdom.StatusTransferred {
			if current.StripeTransferID == stripeTransferID {
				return current, false, nil
			}
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferID
		}

		if err := next.MarkTransferred(stripeTransferID, now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusFailedRetryable:
		errorType := normalizeBrandFeeSettlementOptionalString(patch.ErrorType)
		errorCode := normalizeBrandFeeSettlementOptionalString(patch.ErrorCode)
		errorMsg := normalizeBrandFeeSettlementOptionalString(patch.ErrorMsg)

		if current.Status == brandfeesettlementdom.StatusFailedRetryable &&
			brandFeeSettlementOptionalStringEqual(current.ErrorType, errorType) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorCode, errorCode) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorMsg, errorMsg) {
			return current, false, nil
		}

		if err := next.MarkFailedRetryable(errorType, errorCode, errorMsg, now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusFailed:
		errorType := normalizeBrandFeeSettlementOptionalString(patch.ErrorType)
		errorCode := normalizeBrandFeeSettlementOptionalString(patch.ErrorCode)
		errorMsg := normalizeBrandFeeSettlementOptionalString(patch.ErrorMsg)

		if current.Status == brandfeesettlementdom.StatusFailed &&
			brandFeeSettlementOptionalStringEqual(current.ErrorType, errorType) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorCode, errorCode) &&
			brandFeeSettlementOptionalStringEqual(current.ErrorMsg, errorMsg) {
			return current, false, nil
		}

		if err := next.MarkFailed(errorType, errorCode, errorMsg, now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusCanceled:
		if current.Status == brandfeesettlementdom.StatusCanceled {
			return current, false, nil
		}
		if err := next.Cancel(now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	case brandfeesettlementdom.StatusReversed:
		if patch.StripeTransferReversalID == nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferReversalID
		}

		reversalID := *patch.StripeTransferReversalID
		if current.Status == brandfeesettlementdom.StatusReversed {
			if current.StripeTransferReversalID == reversalID {
				return current, false, nil
			}
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferReversalID
		}

		if err := next.MarkReversed(reversalID, now); err != nil {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, err
		}

	default:
		return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStatus
	}

	if patch.StripeTransferID != nil &&
		nextStatus != brandfeesettlementdom.StatusTransferred {
		if *patch.StripeTransferID != next.StripeTransferID {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferID
		}
	}
	if patch.StripeTransferReversalID != nil &&
		nextStatus != brandfeesettlementdom.StatusReversed {
		if *patch.StripeTransferReversalID != next.StripeTransferReversalID {
			return brandfeesettlementdom.BrandFeeSettlement{}, false, brandfeesettlementdom.ErrInvalidStripeTransferReversalID
		}
	}

	if err := next.Validate(); err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, false, err
	}

	return next, true, nil
}

