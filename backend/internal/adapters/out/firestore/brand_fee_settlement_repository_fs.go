// ListTransferCandidates returns BrandFeeSettlements for which a Stripe
// Transfer task may need to be created or retried.
//
// Candidates:
//
//	ready
//	failed_retryable
//	transferring with UpdatedAt <= StaleBefore
//
// Firestore is queried by one status at a time. Stale filtering, deduplication,
// deterministic ordering, and Limit are applied in memory to avoid additional
// composite indexes.
func (r *BrandFeeSettlementRepositoryFS) ListTransferCandidates(
	ctx context.Context,
	in brandfeesettlementdom.ListTransferCandidatesInput,
) ([]brandfeesettlementdom.BrandFeeSettlement, error) {
	if r == nil || r.Client == nil {
		return nil, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if in.StaleBefore.IsZero() {
		return nil, brandfeesettlementdom.ErrInvalidUpdatedAt
	}
	if in.Limit <= 0 {
		return nil, errors.New("brandFeeSettlement: invalid transfer candidate limit")
	}

	staleBefore := in.StaleBefore.UTC()
	statuses := []brandfeesettlementdom.Status{
		brandfeesettlementdom.StatusReady,
		brandfeesettlementdom.StatusFailedRetryable,
		brandfeesettlementdom.StatusTransferring,
	}

	result := make([]brandfeesettlementdom.BrandFeeSettlement, 0)
	seen := make(map[string]struct{})

	for _, candidateStatus := range statuses {
		settlements, err := r.listByField(ctx, "status", string(candidateStatus))
		if err != nil {
			return nil, err
		}

		for _, settlement := range settlements {
			if settlement.Status == brandfeesettlementdom.StatusTransferring &&
				settlement.UpdatedAt.After(staleBefore) {
				continue
			}
			if _, exists := seen[settlement.ID]; exists {
				continue
			}

			seen[settlement.ID] = struct{}{}
			result = append(result, settlement)
		}
	}

	sort.Slice(result, func(i, j int) bool {
		if result[i].UpdatedAt.Equal(result[j].UpdatedAt) {
			return result[i].ID < result[j].ID
		}
		return result[i].UpdatedAt.Before(result[j].UpdatedAt)
	})

	if len(result) > in.Limit {
		result = result[:in.Limit]
	}

	return result, nil
}

func (r *BrandFeeSettlementRepositoryFS) listByField(
	ctx context.Context,
	field string,
	value string,
) ([]brandfeesettlementdom.BrandFeeSettlement, error) {
	iter := r.col().Where(field, "==", value).Documents(ctx)
	defer iter.Stop()

	result := make([]brandfeesettlementdom.BrandFeeSettlement, 0)

	for {
		snapshot, err := iter.Next()
		if err == iterator.Done {
			break
		}
		if err != nil {
			return nil, err
		}

		settlement, err := docToBrandFeeSettlement(snapshot)
		if err != nil {
			return nil, err
		}

		result = append(result, settlement)
	}

	sort.Slice(result, func(i, j int) bool {
		if result[i].CreatedAt.Equal(result[j].CreatedAt) {
			if result[i].OrderItemIndex == result[j].OrderItemIndex {
				return result[i].ID < result[j].ID
			}
			return result[i].OrderItemIndex < result[j].OrderItemIndex
		}
		return result[i].CreatedAt.Before(result[j].CreatedAt)
	})

	return result, nil
}

