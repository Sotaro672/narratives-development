// BrandFeeSettlementRepositoryFS is the Firestore-backed repository for the
// productBlueprint Brand share generated by consumer resale transactions.
//
// Firestore:
//
//	brandFeeSettlements/{brandFeeSettlementId}
//
// One active resale Order item creates at most one BrandFeeSettlement.
//
// The document ID is deterministic:
//
//	NewID(PaymentID, OrderItemIndex)
//
// BrandFeeSettlement represents only:
//
//	AMOL Stripe Platform -> productBlueprint Brand Stripe Connected Account
//
// It is intentionally separate from primary-sale Settlement and resale seller
// SalesReceivable records.
type BrandFeeSettlementRepositoryFS struct {
	Client *firestore.Client
}

func NewBrandFeeSettlementRepositoryFS(client *firestore.Client) *BrandFeeSettlementRepositoryFS {
	return &BrandFeeSettlementRepositoryFS{Client: client}
}

func (r *BrandFeeSettlementRepositoryFS) col() *firestore.CollectionRef {
	return r.Client.Collection(brandFeeSettlementsCollection)
}

func (r *BrandFeeSettlementRepositoryFS) doc(brandFeeSettlementID string) *firestore.DocumentRef {
	return r.col().Doc(brandFeeSettlementID)
}

