// UpdateByID performs one validated BrandFeeSettlement lifecycle transition.
//
// The current entity is read inside a Firestore transaction. Financial state is
// never changed by blindly patching raw Firestore fields.
func (r *BrandFeeSettlementRepositoryFS) UpdateByID(
	ctx context.Context,
	brandFeeSettlementID string,
	patch brandfeesettlementdom.UpdateBrandFeeSettlementInput,
) (brandfeesettlementdom.BrandFeeSettlement, error) {
	if r == nil || r.Client == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if brandFeeSettlementID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidID
	}

	documentReference := r.doc(brandFeeSettlementID)
	var result brandfeesettlementdom.BrandFeeSettlement

	err := r.Client.RunTransaction(ctx, func(ctx context.Context, transaction *firestore.Transaction) error {
		snapshot, err := transaction.Get(documentReference)
		if err != nil {
			if status.Code(err) == codes.NotFound {
				return brandfeesettlementdom.ErrNotFound
			}
			return err
		}

		current, err := docToBrandFeeSettlement(snapshot)
		if err != nil {
			return err
		}

		next, changed, err := applyBrandFeeSettlementPatch(current, patch, time.Now().UTC())
		if err != nil {
			return err
		}
		if !changed {
			result = current
			return nil
		}

		if err := validateBrandFeeSettlementImmutableFields(current, next); err != nil {
			return err
		}
		if err := next.Validate(); err != nil {
			return err
		}
		if err := transaction.Set(documentReference, brandFeeSettlementToData(next)); err != nil {
			return err
		}

		result = next
		return nil
	})
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}

	return result, nil
}

