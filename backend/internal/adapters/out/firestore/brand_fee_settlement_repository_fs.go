// Create persists one new pending BrandFeeSettlement.
//
// Existing deterministic IDs are never overwritten. ErrConflict is returned so
// payment-success processing can safely retry and resolve the existing record.
func (r *BrandFeeSettlementRepositoryFS) Create(
	ctx context.Context,
	in brandfeesettlementdom.CreateBrandFeeSettlementInput,
) (brandfeesettlementdom.BrandFeeSettlement, error) {
	if r == nil || r.Client == nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, errors.New("brandFeeSettlement: firestore client is nil")
	}
	if in.BrandFeeSettlementID == "" {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidID
	}
	if err := in.Brand.Validate(); err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}
	if in.Status == "" {
		in.Status = brandfeesettlementdom.StatusPending
	}
	if in.Status != brandfeesettlementdom.StatusPending {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidStatus
	}

	expectedID, err := brandfeesettlementdom.NewID(in.PaymentID, in.OrderItemIndex)
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}
	if in.BrandFeeSettlementID != expectedID {
		return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrInvalidID
	}

	now := time.Now().UTC()
	entity, err := brandfeesettlementdom.New(
		in.BrandFeeSettlementID,
		in.OrderID,
		in.PaymentID,
		in.OrderItemIndex,
		in.ResaleID,
		in.Brand,
		in.StripePaymentIntentID,
		in.StripeChargeID,
		in.TransferGroup,
		in.BrandFeeAmount,
		in.Currency,
		now,
	)
	if err != nil {
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}

	_, err = r.doc(entity.ID).Create(ctx, brandFeeSettlementToData(entity))
	if err != nil {
		if status.Code(err) == codes.AlreadyExists {
			return brandfeesettlementdom.BrandFeeSettlement{}, brandfeesettlementdom.ErrConflict
		}
		return brandfeesettlementdom.BrandFeeSettlement{}, err
	}

	return entity, nil
}

